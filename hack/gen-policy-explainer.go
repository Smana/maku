// Command gen-policy-explainer copies the "Holds, agreed, signal-checked" section of
// docs/merge-policies.md into the web bundle, so the policy page's "How merge policies decide"
// renders the docs and keeps no second copy (correctness signals, guidance surface 1).
package main

import (
	"encoding/json"
	"fmt"
	"os"
	"strings"
)

const (
	doc     = "docs/merge-policies.md"
	out     = "web/src/generated/how-policies-decide.ts"
	heading = "## Holds, agreed, signal-checked\n"
)

func main() {
	raw, err := os.ReadFile(doc)
	if err != nil {
		fail(err)
	}
	s := string(raw)
	start := strings.Index(s, heading)
	if start < 0 {
		fail(fmt.Errorf("%s lacks %q", doc, strings.TrimSpace(heading)))
	}
	rest := s[start+len(heading):]
	end := strings.Index(rest, "\n## ")
	if end < 0 {
		end = len(rest)
	}
	section, err := json.Marshal(strings.TrimSpace(rest[:end]))
	if err != nil {
		fail(err)
	}
	body := "// SPDX-License-Identifier: Apache-2.0\n\n// Generated by hack/gen-policy-explainer.go from docs/merge-policies.md: do not edit.\n" +
		"export const HOW_POLICIES_DECIDE = " + string(section) + ";\n"
	if err := os.WriteFile(out, []byte(body), 0o644); err != nil { //nolint:gosec // a generated source file
		fail(err)
	}
}

func fail(err error) {
	fmt.Fprintln(os.Stderr, "gen-policy-explainer:", err)
	os.Exit(1)
}
